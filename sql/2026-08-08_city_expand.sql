-- Expand the city list to cover birth places properly.
--
-- 200 cities was enough for "where do you live" but not for "where were you
-- born" - people are born in district towns, and anything not on the list ended
-- up as free text, which is how the profile table came to contain "Nihal",
-- "Hdhdjd" and "Bareily". A kundali cannot be calculated from those.
--
-- Adds every Indian settlement in the geonames dataset with a population of
-- 50,000 or more, with coordinates. State is resolved through geonames' admin1
-- code, and that code-to-state mapping was DERIVED from the 200 cities already
-- in this table rather than typed from memory: for each admin1 code, the state
-- that the majority of already-known cities in it belong to. All 35 codes
-- resolved that way, so no city is filed under a guessed state.
--
-- Names are transliterated to ASCII deliberately. The column is utf8mb4, but a
-- member typing "Jhansi" into a search box must match, and the dataset stores
-- "Jhānsi".
--
-- INSERT IGNORE, because (name, state_id) is unique and the 200 existing rows
-- must keep their ids - profiles reference cities by name, and renumbering
-- would orphan them.
--
-- Tier here is a search-ranking hint, not a claim about the place: 2 for
-- population over 500k, 3 otherwise. The existing tier-1 metros are untouched.
-- A few geonames records carry a district's population rather than the town's,
-- so a handful of small places rank higher than they deserve. Harmless for a
-- picker, and not worth hand-curating a thousand rows to fix.
--
-- Safe to run twice.

